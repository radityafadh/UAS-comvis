"""#2. Penentuan Fungsi Rumus"""

def load_gray(p):
    """Baca citra -> grayscale (ukuran asli, tanpa resize)."""
    img = cv2.imread(p)
    return None if img is None else cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)


def resize_aspect_ratio(img, min_size=600):
    """Resize citra dengan mempertahankan aspek rasio agar dimensi terkecil minimal min_size."""
    if img is None:
        return None
    h, w = img.shape[:2]
    if h < w:
        new_h = min_size
        new_w = int(w * (min_size / h))
    else:
        new_w = min_size
        new_h = int(h * (min_size / w))
    return cv2.resize(img, (new_w, new_h), interpolation=cv2.INTER_AREA)


def tampil(img, judul):
    """Tampilkan citra + histogramnya."""
    fig, ax = plt.subplots(1, 2, figsize=(10, 3.5))
    ax[0].imshow(img, cmap="gray", vmin=0, vmax=255)
    ax[0].set_title(f"{judul} {img.shape}")
    ax[0].axis("off")
    ax[1].hist(img.ravel(), bins=256, range=(0, 256), color="gray")
    ax[1].set_title(f"Histogram {judul}")
    plt.tight_layout()
    plt.show()


