def proses_varian(v):
    """Fitur (13: 7 Gabor + 6 bentuk) + tafsir + MSE/PSNR (Gabor & Otsu vs grayscale resized), untuk SEMUA citra varian v."""
    sub = meta[meta["Varian"] == v]
    rows, gagal, tanpa_ref = [], 0, 0

    for _, r in tqdm(sub.iterrows(), total=len(sub), desc=v):
        img = cv2.imread(r["Path"], cv2.IMREAD_GRAYSCALE)
        if img is None:
            gagal += 1
            continue

        m_g = p_g = m_b = p_b = np.nan
        p_ref = f"{REF_DIR}/{r['Buah']} fruit/{r['Sampel']}/02_grayscale_resized.png"
        ref = cv2.imread(p_ref, cv2.IMREAD_GRAYSCALE) if os.path.exists(p_ref) else None
        if ref is not None and ref.shape == img.shape:
            m_g, p_g = mse_psnr(ref, gabor_8bit(img))     # Gabor  vs gray
            m_b, p_b = mse_psnr(ref, bentuk_gray(img))    # Bentuk vs gray
        else:
            tanpa_ref += 1

        rows.append({"Varian": v, "Buah": r["Buah"], "Sampel": r["Sampel"], "Sampel_No": r["Sampel_No"],
                    **extract_features(img),
                    "MSE_Gabor": m_g, "PSNR_Gabor": p_g,
                    "MSE_Bentuk": m_b, "PSNR_Bentuk": p_b})

    df = (pd.DataFrame(rows).replace(np.inf, np.nan)
            .sort_values(["Buah", "Sampel_No"]).reset_index(drop=True))
    df["Tafsir_Tekstur"] = df.apply(lambda r: tafsir_tekstur(r[GABOR_COLS].astype(float), df), axis=1)
    df["Tafsir_Bentuk"]  = df.apply(tafsir_bentuk, axis=1)
    print(f"{v}: {len(df)} citra | gagal dibaca: {gagal} | tanpa pembanding: {tanpa_ref}")
    return df, dict(zip(zip(sub["Buah"], sub["Sampel"]), sub["Path"]))


