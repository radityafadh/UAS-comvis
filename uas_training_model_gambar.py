"""#3. Muat citra ke memori + Dataset"""

MEAN = torch.tensor([0.485, 0.456, 0.406]).view(3, 1, 1)
STD  = torch.tensor([0.229, 0.224, 0.225]).view(3, 1, 1)


def muat_array(paths, desc=""):
    """Baca grayscale, resize 224x224, simpan uint8 di RAM (sekali baca dari Drive)."""
    arr = np.zeros((len(paths), IMG_SIZE, IMG_SIZE), np.uint8)
    for i, p in enumerate(tqdm(paths, desc=desc)):
        img = cv2.imread(p, cv2.IMREAD_GRAYSCALE)
        arr[i] = cv2.resize(img, (IMG_SIZE, IMG_SIZE), interpolation=cv2.INTER_AREA)
    return arr


class CitraDataset(Dataset):
    def __init__(self, arr, labels, train=False):
        self.arr, self.labels, self.train = arr, labels, train

    def __len__(self):
        return len(self.arr)

    def __getitem__(self, i):
        x = torch.from_numpy(self.arr[i]).unsqueeze(0).float() / 255.0     # 1 x H x W
        if self.train:                                                      # augmentasi ringan (tanpa ubah intensitas)
            if random.random() < 0.5:
                x = TF.hflip(x)
            if random.random() < 0.5:
                x = TF.vflip(x)
            x = TF.rotate(x, random.uniform(-15, 15))
        x = x.repeat(3, 1, 1)                                               # 1 channel -> 3 channel
        x = (x - MEAN) / STD                                                # normalisasi ImageNet
        return x, int(self.labels[i])


def buat_loader(df, arr):
    loaders = {}
    for sp in ["train", "val", "test"]:
        idx = np.where(df["Split"].values == sp)[0]
        ds = CitraDataset(arr[idx], df["Label"].values[idx], train=(sp == "train"))
        loaders[sp] = DataLoader(ds, batch_size=BATCH, shuffle=(sp == "train"),
                                 num_workers=2, pin_memory=True)
    return loaders

"""#4. Pembuat model (pretrained, 9 kelas)"""

def buat_model(nama, n_kelas=len(KELAS)):
    if nama == "efficientnet_b0":
        m = models.efficientnet_b0(weights=models.EfficientNet_B0_Weights.DEFAULT)
        m.classifier[1] = nn.Linear(m.classifier[1].in_features, n_kelas)
    elif nama == "resnet50":
        m = models.resnet50(weights=models.ResNet50_Weights.DEFAULT)
        m.fc = nn.Linear(m.fc.in_features, n_kelas)
    else:
        raise ValueError(nama)
    return m.to(DEVICE)

"""#5. Fungsi train dan evaluasi"""

@torch.no_grad()
def evaluasi(model, loader, crit):
    model.eval()
    tot_loss, preds, gts = 0.0, [], []
    for x, y in loader:
        x, y = x.to(DEVICE), y.to(DEVICE)
        with torch.autocast(device_type="cuda", enabled=(DEVICE == "cuda")):
            out = model(x)
            loss = crit(out, y)
        tot_loss += loss.item() * len(y)
        preds += out.argmax(1).cpu().tolist()
        gts   += y.cpu().tolist()
    return tot_loss / len(gts), np.array(preds), np.array(gts)


def latih(model, loaders, epochs=EPOCHS, lr=LR):
    crit = nn.CrossEntropyLoss()
    opt  = torch.optim.Adam(model.parameters(), lr=lr)
    scaler = torch.cuda.amp.GradScaler(enabled=(DEVICE == "cuda"))
    hist = dict(train_loss=[], val_loss=[], train_acc=[], val_acc=[])
    best_acc, best_state = -1, None

    for ep in range(epochs):
        model.train()
        tl, tp, tg = 0.0, [], []
        for x, y in loaders["train"]:
            x, y = x.to(DEVICE), y.to(DEVICE)
            opt.zero_grad()
            with torch.autocast(device_type="cuda", enabled=(DEVICE == "cuda")):
                out = model(x)
                loss = crit(out, y)
            scaler.scale(loss).backward()
            scaler.step(opt); scaler.update()
            tl += loss.item() * len(y)
            tp += out.argmax(1).cpu().tolist(); tg += y.cpu().tolist()

        vl, vp, vg = evaluasi(model, loaders["val"], crit)
        ta, va = accuracy_score(tg, tp), accuracy_score(vg, vp)
        hist["train_loss"].append(tl / len(tg)); hist["val_loss"].append(vl)
        hist["train_acc"].append(ta);            hist["val_acc"].append(va)
        print(f"  ep {ep+1:02d}/{epochs} | train acc {ta:.3f} | val acc {va:.3f} | val loss {vl:.3f}")

        if va > best_acc:                                   # simpan bobot terbaik di RAM (tanpa file)
            best_acc, best_state = va, copy.deepcopy(model.state_dict())

    model.load_state_dict(best_state)
    return model, hist, best_acc

