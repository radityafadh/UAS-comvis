# ---------- main loop ----------
for exp in EXPERIMEN_FILE:
    pre, inp = exp.split("_")[0], exp.split("_")[1]     # match your original CSV schema

    # skip the whole exp if every model is already done
    pending = [m for m in MODELS if (pre, inp, m) not in done_keys]
    if not pending:
        print(f"[skip] {exp} — all models already done")
        continue

    # only now do we pay for loading images / reading Drive
    df  = siapkan_df(exp)
    arr = muat_array(df["Path"].tolist(), desc=f"muat {exp}")

    for nama_model in MODELS:
        key = (pre, inp, nama_model)

        # ---- RESUME: skip models already finished ----
        if key in done_keys:
            print(f"[skip] {exp} | {nama_model} (already done)")
            continue

        print("\n" + "=" * 60 + f"\n{exp}  |  {nama_model}\n" + "=" * 60)

        try:
            set_seed()
            loaders = buat_loader(df, arr)
            model   = buat_model(nama_model)

            t0 = time.time()
            model, hist, best_val = latih(model, loaders)
            _, p, g = evaluasi(model, loaders["test"], nn.CrossEntropyLoss())

            acc = accuracy_score(g, p)
            f1  = f1_score(g, p, average="macro")
            print(f"TEST | acc {acc:.4f} | macro-F1 {f1:.4f} | {time.time()-t0:.0f} detik")

            CM[key]   = confusion_matrix(g, p)
            HIST[key] = hist
            simpan_png(key, hist, CM[key])
            hasil.append(dict(Preprocessing=pre, Input=inp, Model=nama_model,
                              Val_Acc=round(best_val, 4), Test_Acc=round(acc, 4),
                              Test_MacroF1=round(f1, 4),
                              Waktu_detik=round(time.time() - t0)))

            # ---- CHECKPOINT: persist immediately ----
            save_progress()
            done_keys.add(key)
            print(f"[ckpt] saved -> {OUT_CSV}")

        except Exception as e:
            # one model failing shouldn't kill the whole sweep
            print(f"[ERR] {key}: {type(e).__name__}: {e}")

        finally:
            try:
                del model, loaders
            except Exception:
                pass
            torch.cuda.empty_cache()

    del arr

# final save (already done inside the loop, but harmless)
